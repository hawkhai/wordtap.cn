import { readFile, stat, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const courses = [
  ["nce", "books"], ["shuimu", "levels"], ["postgraduate", "volumes"],
  ["pep-english", "groups"], ["college-english", "groups"],
  ["cet", "groups"], ["kaoyan-english", "groups"],
];

export async function buildSearchRedirects(distDir) {
  const owners = new Map();
  const rules = [];
  for (const [course, collections] of courses) {
    const manifest = JSON.parse(await readFile(path.join(distDir, course, "manifest.json"), "utf8"));
    const ids = manifest[collections].flatMap((group) => group.lessons.map((lesson) => lesson.id)).sort();
    for (const id of ids) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) throw new Error(`Unsafe lesson id: ${id}`);
      if (owners.has(id)) throw new Error(`Ambiguous root lesson path: ${id}`);
      owners.set(id, course);
      if (!(await stat(path.join(distDir, course, id, "index.html"))).isFile()) {
        throw new Error(`Redirect target is not a published page: ${course}/${id}`);
      }
      // Never shadow a real root file or directory.
      try {
        await stat(path.join(distDir, id));
        throw new Error(`Root lesson alias conflicts with an existing path: ${id}`);
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
    }
    // Explicit published IDs only: unknown paths still return a real 404.
    // Nginx rewrite preserves the original query string automatically.
    rules.push(`rewrite ^/(${ids.join("|")})/?$ https://wordtap.cn/${course}/$1/ permanent;`);
  }
  return { count: owners.size, config: [
    "# Generated by npm run generate:search-redirects; do not edit by hand.",
    "# Include in the WordTap Nginx server block, before a generic return/rewrite.",
    ...rules, "",
  ].join("\n") };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const result = await buildSearchRedirects(path.resolve("dist"));
  const target = path.resolve("deployment/nginx/wordtap-lesson-redirects.conf");
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, result.config, "utf8");
  console.log(`Generated Nginx redirects for ${result.count} published root lesson paths.`);
}
